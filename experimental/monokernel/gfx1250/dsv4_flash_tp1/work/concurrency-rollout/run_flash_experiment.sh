#!/bin/bash
set -euo pipefail
mode=${1:?Usage: run_flash_experiment.sh baseline|full-c1|qkv-hybrid|client TAG CONCURRENCY}
export ATOM_DSV4_FULL_LAYER_EXPERIMENTAL=0 ATOM_DSV4_MODELWIDE=0
unset ATOM_DSV4_BATCH_QKV_NATIVE_CONTROL ATOM_DSV4_DUAL_REGION ATOM_DSV4_BATCH_SERIAL ATOM_DSV4_BATCH_QA ATOM_DSV4_BATCH_QKV ATOM_DSV4_BATCH_QKV_NATIVE_TAIL ATOM_DSV4_MODELWIDE_VALIDATE ATOM_DSV4_NATIVE_STATE
unset ATOM_DSV4_BATCH_QKV_CLONE_OUTPUT ATOM_DSV4_BATCH_QKV_NATIVE_SCATTER ATOM_DSV4_BATCH_QKV_GUARD ATOM_DSV4_BATCH_QKV_DIRECT_KV ATOM_DSV4_BATCH_QKV_PREALLOC ATOM_DSV4_BATCH_QKV_SHADOW ATOM_DSV4_BATCH_QKV_AUDIT ATOM_DSV4_BATCH_QKV_LATE_TDM
unset ATOM_DSV4_BATCH_QKV_QA_ONLY ATOM_DSV4_BATCH_QKV_SPLIT_INPUT ATOM_DSV4_BATCH_QKV_SPLIT_NORM ATOM_DSV4_BATCH_QKV_INPUT_ONLY ATOM_DSV4_BATCH_QKV_PREFETCH_ONLY ATOM_DSV4_BATCH_QKV_NO_PREFETCH ATOM_DSV4_BATCH_QKV_SYNC_STYLE ATOM_DSV4_BATCH_QKV_PREFETCH_STYLE
case "$mode" in
 baseline) exec bash /work/concurrency-rollout/server.sh;;
 full-c1)
  export ATOM_DSV4_FULL_LAYER_EXPERIMENTAL=1 ATOM_DSV4_MODELWIDE=1 ATOM_DSV4_MODELWIDE_MAX_CONTEXT=2048
  export ATOM_DSV4_MATCHED_ATTN=1 ATOM_DSV4_PRECISE_MHC=1 ATOM_DSV4_STATE_DISPATCH=1
  export CONCURRENCY=1 CAPTURE_SIZES='[1]'
  exec bash /work/concurrency-rollout/server.sh;;
 qkv-hybrid)
  echo 'Experimental QKV-only fusion across all layers; see /work/concurrency-rollout/REPORT.md for known limitations.'
  export ATOM_DSV4_BATCH_QKV=1
  exec bash /work/concurrency-rollout/server.sh;;
 client) exec bash /work/concurrency-rollout/clients.sh "${2:?result tag}" "${HTTP_PORT:-8000}" "${3:?concurrency}";;
 *) echo 'Unknown mode' >&2; exit 2;;
esac
