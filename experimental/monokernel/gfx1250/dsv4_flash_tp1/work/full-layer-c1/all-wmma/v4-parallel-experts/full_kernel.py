from ops import *

@g.jit
def all_wmma_layer(R, Out, Token, Cache, Cos, Sin, HAF, HAS, HAB, HFN, HFS, HFB, AN, FN, QN, KN, Sink, QA, QAS, QB, QBS, KVW, KVS, OA, OAS, OB, OBS, SW1, SS1, SW3, SS3, SW2, SS2, Gate, Tid, EW1, ES1, EW3, ES3, EW2, ES2, MixA, MixF, R2, X, XQ, QL, QLQ, Q, KV, QRot, KVRot, AO, AR, AQ, OL, OLQ, Attn, FF, FFQ, FFMX, SG, SU, SA, SAQ, SO, Logits, Ids, Gamma, EG, EU, EA, EAQ, EO, Sum, Counter, Health, GRID: gl.constexpr=64, REGION: gl.constexpr=0, XP=None, XS=None, LP=None, LS=None, QPART=None, KPART=None, MHC_TEMP=None):
    mhc_wmma(R, HAF, HAS, HAB, MixA, MHC_TEMP, Counter, Health, GRID)
    sync(Counter, Health, GRID)
    sinkhorn(MixA)
    sync(Counter, Health, GRID)
    mhc_pre(R, MixA, X, GRID)
    sync(Counter, Health, GRID)
    norm(X, AN, X, 4096, 1, True, GRID)
    sync(Counter, Health, GRID)
    quant(X, XQ, 4096, 128, GRID)
    sync(Counter, Health, GRID)
    pack(XQ, XQ, XP, XS, 4096, GRID)
    sync(Counter, Health, GRID)
    wmma_matvec(XP, XS, QA, QAS, QPART, 1024, 4096, GRID, 32, 8)
    wmma_matvec(XP, XS, KVW, KVS, KPART, 512, 4096, GRID, 32, 8)
    sync(Counter, Health, GRID)
    partial_norm(QPART, QN, QL, 1024, 8)
    partial_norm(KPART, KN, KV, 512, 8)
    sync(Counter, Health, GRID)
    pack(QL, QLQ, LP, LS, 1024, GRID)
    sync(Counter, Health, GRID)
    wmma_matvec(LP, LS, QB, QBS, Q, 32768, 1024, GRID, 128)
    sync(Counter, Health, GRID)
    norm(Q, QN, Q, 512, 64, False, GRID, False)
    sync(Counter, Health, GRID)
    rope(Q, Cos, Sin, QRot, 64, False, GRID)
    rope(KV, Cos, Sin, KVRot, 1, False, GRID)
    sync(Counter, Health, GRID)
    if gl.program_id(0) == 0:
        i = gl.arange(0, 512, layout=gl.BlockedLayout([1], [32], [4], [0]))
        dev_store(dev_load(KVRot, i, cache='.cg'), Cache, 127 * 512 + i, cache='.cg')
    sync(Counter, Health, GRID)
    attention_wmma(QRot, KVRot, Cache, Sink, AO, GRID)
    sync(Counter, Health, GRID)
    rope(AO, Cos, Sin, AR, 64, True, GRID)
    sync(Counter, Health, GRID)
    quant(AR, AQ, 32768, 128, GRID)
    sync(Counter, Health, GRID)
    linear(AQ, OA, OAS, OL, 8192, 4096, 8, GRID, True)
    sync(Counter, Health, GRID)
    quant(OL, OLQ, 8192, 128, GRID)
    sync(Counter, Health, GRID)
    linear(OLQ, OB, OBS, Attn, 4096, 8192, 8, GRID)
    sync(Counter, Health, GRID)
    mhc_post(Attn, R, MixA, R2, GRID)
    sync(Counter, Health, GRID)
    mhc_wmma(R2, HFN, HFS, HFB, MixF, MHC_TEMP, Counter, Health, GRID)
    sync(Counter, Health, GRID)
    sinkhorn(MixF)
    sync(Counter, Health, GRID)
    mhc_pre(R2, MixF, FF, GRID)
    sync(Counter, Health, GRID)
    norm(FF, FN, FF, 4096, 1, True, GRID)
    sync(Counter, Health, GRID)
    quant(FF, FFQ, 4096, 128, GRID)
    quant(FF, FFMX, 4096, 32, GRID)
    linear(FF, Gate, Gate, Logits, 256, 4096, 16, GRID)
    sync(Counter, Health, GRID)
    route(Logits, Tid, Token, Ids, Gamma)
    linear(FFQ, SW1, SS1, SG, 2048, 4096, 8, GRID)
    linear(FFQ, SW3, SS3, SU, 2048, 4096, 8, GRID)
    sync(Counter, Health, GRID)
    activation(SG, SU, SA, 2048, GRID)
    sync(Counter, Health, GRID)
    quant(SA, SAQ, 2048, 128, GRID)
    sync(Counter, Health, GRID)
    linear(SAQ, SW2, SS2, SO, 4096, 2048, 8, GRID)
    routed_linear(FFMX, EW1, ES1, EG, 2048, 4096, 4, GRID, FLOAT_OUT=True, Ids=Ids)
    routed_linear(FFMX, EW3, ES3, EU, 2048, 4096, 4, GRID, FLOAT_OUT=True, Ids=Ids)
    sync(Counter, Health, GRID)
    activation(EG, EU, EA, 6 * 2048, GRID, False)
    sync(Counter, Health, GRID)
    quant(EA, EAQ, 6 * 2048, 32, GRID)
    sync(Counter, Health, GRID)
    routed_linear(EAQ, EW2, ES2, EO, 4096, 2048, 4, GRID, Gamma=Gamma, Ids=Ids, PER_EXPERT_INPUT=True)
    sync(Counter, Health, GRID)
    i = gl.arange(0, 256, layout=gl.BlockedLayout([1], [32], [4], [0]))
    for tile in range(gl.program_id(0), 16, GRID):
        c = tile * 256 + i
        value = gl.full((256,), 0.0, gl.float32, gl.BlockedLayout([1], [32], [4], [0]))
        for reduce_slot in gl.static_range(6):
            value += dev_load(EO, reduce_slot * 4096 + c, cache='.cg').to(gl.float32)
        value = value.to(gl.bfloat16).to(gl.float32) + dev_load(SO, c, cache='.cg').to(gl.float32)
        dev_store(value.to(gl.bfloat16), Sum, c, cache='.cg')
    sync(Counter, Health, GRID)
    mhc_post(Sum, R2, MixF, Out, GRID)
