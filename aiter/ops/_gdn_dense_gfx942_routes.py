def _pack_shape_key(b: int, t: int, h: int, state_on: bool) -> int | None:
    """Pack a validated shape key without the two path bits."""

    if (
        type(b) is not int
        or type(t) is not int
        or type(h) is not int
        or type(state_on) is not bool
    ):
        return None
    if not (1 <= b <= _B_MAX) or not (1 <= h <= _H_MAX):
        return None
    if t <= 0 or t % 64:
        return None

    t64 = t // 64
    if not (1 <= t64 <= _T64_MAX):
        return None

    return (((b << _T64_BITS) | t64) << _H_BITS | h) << 1 | int(state_on)


def lookup_dense_gfx942_path(b: int, t: int, h: int, state_on: bool) -> str | None:
    """Return the exact measured winner (cf/cs/ws/wf), or None."""

    key = _pack_shape_key(b, t, h, state_on)
    if key is None:
        return None

    index = bisect_left(_PACKED_ROUTES, key << _PATH_BITS)
    if index == DENSE_GFX942_RECORD_COUNT:
        return None

    record = _PACKED_ROUTES[index]
    if record >> _PATH_BITS != key:
        return None
    return _PATHS[record & ((1 << _PATH_BITS) - 1)]
