"""MoE GEMM with 16-bit activations and 16-bit weights (gfx1250 Gluon)."""

import torch
import triton

from aiter.ops.triton._gluon_kernels.gfx1250.moe.moe_op_gemm_a16w16 import (
    _moe_gemm_a16w16,
    get_moe_a16w16_layouts,
)
from aiter.ops.triton.moe.moe_routing.routing import RoutingData
from aiter.ops.triton.moe.reduce import reduce_grouped
from aiter.ops.triton.utils._triton.arch_info import get_arch
from aiter.ops.triton.utils.logger import AiterTritonLogger
from aiter.ops.triton.utils.moe_common import can_overflow_int32
from aiter.ops.triton.utils.moe_config_utils import get_moe_dispatch, m2bucket

_LOGGER = AiterTritonLogger()

_SUPPORTED_ARCHS = ("gfx1250",)


def should_upcast_indices(*args):
    return any(tensor is not None and can_overflow_int32(tensor) for tensor in args)


def allocate_output(
    M,
    N,
    out_dtype,
    reduction_n_matmul,
    reduction_n_reduction,
    routing_data,
    scatter_indx,
    split_k,
    device,
):
    if routing_data.n_expts_act == 1 or scatter_indx is None:
        y_rows = M
    else:
        # compressed number of rows
        y_rows = scatter_indx.shape[0] // routing_data.n_expts_act
    matmul_shape = (split_k, M, N // reduction_n_matmul)
    final_shape = (y_rows, N // reduction_n_matmul // reduction_n_reduction)
    matmul_output = torch.empty(matmul_shape, device=device, dtype=out_dtype)
    if scatter_indx is not None or split_k > 1:
        final_output = torch.empty(final_shape, device=device, dtype=out_dtype)
    else:
        final_output = None
    return matmul_output, final_output


def get_kernel_config_gluon(m, n, k, routing_data, apply_swiglu=False):
    """Tuned config for one call.

    A call that fuses SwiGLU needs its own entry. The epilogue splits the whole
    BLOCK_M x BLOCK_N accumulator, so it spills above block_n=128: 260 spilled
    registers at 256 and 516 at 512, which costs 10x. A call without SwiGLU
    prefers the wider tile, so the two cannot share one entry.
    """
    block_m = routing_data.block_m

    tuned = get_moe_dispatch("A16W16", get_arch(), "gluon")
    suffix = "_swiglu" if apply_swiglu else ""
    for key in (
        f"bm{block_m}{suffix}_n{n}_k{k}_{m2bucket(m)}",
        f"bm{block_m}{suffix}_any",
        f"bm{block_m}_any",
    ):
        if key in tuned:
            break
    cfg = tuned[key]

    block_k = cfg["block_k"]
    # The steady-state loop runs num_k_iter - (num_buffers - 1) times, so the
    # pipeline cannot be deeper than the number of K tiles.
    num_buffers = min(cfg["num_buffers"], triton.cdiv(k, block_k))

    config = dict(cfg)
    # block_m comes from routing, and the pipeline cannot be deeper than K.
    config["block_m"] = block_m
    config["num_buffers"] = num_buffers
    return config


def moe_gemm_a16w16(
    x: torch.Tensor,
    w: torch.Tensor,
    x_scales=None,  # API compatibility with lower-precision MoE ops; must be None
    w_scales=None,  # API compatibility with lower-precision MoE ops; must be None
    x_static_scale=None,  # API compatibility; must be None
    quant_static_scale=None,  # API compatibility; must be None
    bias=None,
    routing_data: RoutingData | None = None,
    gather_indx=None,
    scatter_indx=None,
    gammas=None,
    out_dtype=torch.bfloat16,
    apply_swiglu=False,
    alpha=1.0,
    limit=1.0,
    swiglu_add_residual=True,
    unpadded_N=None,
    unpadded_K=None,
    backend: str | None = None,
):
    """
    Computes MoE GEMM with 16-bit activations and 16-bit weights.

    Y[:, :] = 0.
    for e in num_experts:
        Y[idxs_y_m(e), :] += matmul(X[idxs_x_m(e), :], W[e, :, :])

    Args:
        x (torch.Tensor): Activations with shape (num_tokens, K/hidden_dim). Must be 16-bit
        w (torch.Tensor): Weight tensor with shape (E/num_experts_total, K/hidden_dim, N/int_dim).
            Must be 16-bit and N-contiguous (``w.stride(-1) == 1``)
        x_scales: Must be None since activations are 16-bit
        w_scales: Must be None since weights are 16-bit
        x_static_scale: Must be None
        quant_static_scale: Must be None
        bias(torch.Tensor): Optional bias tensor
        routing_data: Generated by the routing kernels
        gather_indx: Generated along with routing data by routing kernels
        scatter_indx: Generated along with routing data by routing kernels
        gammas(torch.Tensor): Optional gammas tensor
        out_dtype(dtype): output dtype
        apply_swiglu(bool): Whether to apply swiglu activation
        alpha(float): swiglu alpha
        limit(float): swiglu clamp limit
        swiglu_add_residual(bool): Whether to add swiglu residual
        backend(Optional[str]): "gluon" or None. Only the gluon backend exists
            for this op, and only on gfx1250.

    Returns:
        torch.Tensor: Output with shape (num_tokens, N) or, with swiglu, (num_tokens, N // 2)
    """
    arch = get_arch()
    assert arch in _SUPPORTED_ARCHS, (
        f"moe_gemm_a16w16 is only implemented for {_SUPPORTED_ARCHS}, got {arch}. "
        "There is no triton fallback for this op."
    )
    if backend is not None:
        assert (
            backend.lower() == "gluon"
        ), f"Unknown backend '{backend}', moe_gemm_a16w16 only has a 'gluon' backend"

    assert x_scales is None, "x_scales must be none"
    assert w_scales is None, "w_scales must be none"
    assert x_static_scale is None, "x_static_scale must be none"
    assert quant_static_scale is None, "quant_static_scale must be none"
    assert x.dtype.itemsize == 2, f"x must be 16-bit, got {x.dtype}"
    assert w.dtype.itemsize == 2, f"w must be 16-bit, got {w.dtype}"
    assert w.stride(-1) == 1, "`w` must be N-contiguous, i.e. (E, K, N) row-major"

    _LOGGER.info(
        "MOE_GEMM_A16W16: x=%s w=%s bias=%s apply_swiglu=%s",
        x.shape,
        w.shape,
        None if bias is None else bias.shape,
        apply_swiglu,
    )

    # determine shapes
    M = x.shape[-2] if gather_indx is None else gather_indx.shape[0]
    K, N = x.shape[-1], w.shape[-1]
    block_m = routing_data.block_m
    if unpadded_N and block_m == 16:
        N = unpadded_N
    if unpadded_K and block_m == 16:
        K = unpadded_K

    config = get_kernel_config_gluon(M, N, K, routing_data, apply_swiglu)

    if apply_swiglu:
        apply_swiglu_matmul = True
        reduction_n_matmul = 2
        apply_swiglu_reduction = False
        reduction_n_reduction = 1
    else:
        apply_swiglu_matmul = False
        reduction_n_matmul = 1
        apply_swiglu_reduction = False
        reduction_n_reduction = 1

    # allocate output memory
    y, y_final = allocate_output(
        M,
        N,
        out_dtype,
        reduction_n_matmul,
        reduction_n_reduction,
        routing_data,
        scatter_indx,
        config["split_k"],
        x.device,
    )
    stride_bias = None if bias is None else bias.stride(0)

    # moe metadata
    expt_data = routing_data.expt_data
    expt_hist = None if expt_data is None else expt_data.hist
    expt_hist_sum = None if expt_data is None else expt_data.token_offs_pad[-1]
    expt_token_offs_raw = None if expt_data is None else expt_data.token_offs_raw
    expt_block_pid_map = None if expt_data is None else expt_data.block_pid_map

    # spmd grid
    grid_m = routing_data.n_blocks(M, config["block_m"])
    grid_n = triton.cdiv(N, config["block_n"])
    grid = grid_m * grid_n * config["split_k"]

    _moe_gemm_a16w16[(grid,)](
        y,
        y.stride(0),
        y.stride(1),
        y.stride(2),
        x,
        x.stride(0),
        x.stride(1),
        w,
        w.stride(0),  # stride_w_e
        w.stride(1),  # stride_w_k
        w.stride(2),  # stride_w_n
        bias,
        stride_bias,
        gammas,
        M,
        N,
        K,
        gather_indx,
        expt_hist,
        expt_token_offs_raw,
        expt_hist_sum,
        expt_block_pid_map,
        grid_m,
        grid_n,
        apply_swiglu_matmul,
        alpha,
        limit,
        reduction_n_matmul,
        swiglu_add_residual,
        routing_data.n_expts_act,
        config["block_m"],
        config["block_n"],
        config["block_k"],
        config["group_m"],
        XCD_SWIZZLE=config["xcd_swizzle"],
        NUM_BUFFERS=config["num_buffers"],
        NUM_SUBTILES=config["num_subtiles"],
        EVEN_K=K % config["block_k"] == 0,
        **get_moe_a16w16_layouts(
            config["num_warps"],
            config["block_m"],
            config["block_n"],
            config["block_k"],
            config["block_n"] // reduction_n_matmul,
            config["num_ctas"],
            (
                16
                if (gather_indx is not None and gather_indx.dtype == torch.uint16)
                else 8
            ),
            config["cluster_split"],
        ),
        num_warps=config["num_warps"],
        UPCAST_INDICES=should_upcast_indices(x, w, y),
        waves_per_eu=config["waves_per_eu"],
        num_ctas=config["num_ctas"],
    )

    group_indx = (
        None
        if scatter_indx is None
        else scatter_indx.view(-1, routing_data.n_expts_act)
    )
    y_final = reduce_grouped(
        y,
        group_indx,
        y_final,
        apply_swiglu_reduction,
        alpha,
        limit,
        reduction_n_reduction,
        out_dtype=out_dtype,
        swiglu_add_residual=swiglu_add_residual,
    )

    return y_final
