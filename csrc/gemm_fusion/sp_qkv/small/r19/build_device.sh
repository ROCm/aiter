#!/usr/bin/env bash
# SM-T1-r5x device recipe (env MODE=indexer|reuse added; one build per mode; host build must use the same MODE) (env B_HEADS=1|2, U2=1|0 added) (Track 1; static roles grid 53; P0=1 P1=1 are the r3 variant-B defaults) (adds P0=1 P1=0 P2=0 P3=0 env; P3=1 needs host P3=1 too) (variants via env: STAMPS=0/1, R1=1/0, R2=0/1, R3=1/0, R4=1/0; defaults R1=1 R2=0 R3=1 R4=1 STAMPS=0).
# STAMPS=1 is a SEPARATE diagnostic binary (never used for candidate timing). Use a fresh BUILD_DIR per variant.
# (r1 header follows) SM-SK2-RAN-r1 device recipe (source-only; NOT executed). Two HSACOs (sk_gemm, RAN), explicit gfx950.
# Generates gen/sm_expected_hashes.h from the actual code-object hashes. Fresh BUILD_DIR mandatory.
set -euo pipefail
CAND="${CAND:-/work/candidates/SM-SK2-RAN-r1}"
PR695="${PR695:-/work/candidates/PR695-M4}"      # read-only source of private_deps (opus headers)
MORI_ROOT="${MORI_ROOT:-/reference-mori}"
HIPCC="${HIPCC:-/opt/rocm/bin/hipcc}"
BUNDLER="${BUNDLER:-/opt/rocm/llvm/bin/clang-offload-bundler}"
OBJCOPY="${OBJCOPY:-objcopy}"
BUILD_DIR="${BUILD_DIR:?set BUILD_DIR to a fresh, non-existent output directory}"
[ -e "${BUILD_DIR}" ] && { echo "refuse: BUILD_DIR exists (${BUILD_DIR})" >&2; exit 1; }
bash -n "${BASH_SOURCE[0]}"
( cd "${CAND}" && sha256sum -c SOURCE_SHA256.txt )
mkdir -p "${BUILD_DIR}/gen" "${BUILD_DIR}/img"
P0="${P0:-1}"; P1="${P1:-1}"; P2="${P2:-0}"; STAMPS="${STAMPS:-0}"; R1="${R1:-1}"; R2="${R2:-0}"; R3="${R3:-1}"; R4="${R4:-1}"
B_HEADS="${B_HEADS:-2}"; U2="${U2:-1}"; MODE="${MODE:-indexer}"; DENSE=0; case "${MODE}" in indexer) IDX=1;; reuse) IDX=0;; dense) IDX=0; DENSE=1;; *) echo "MODE must be indexer, reuse or dense" >&2; exit 2;; esac
VARDEFS=( -DSM_R5X_INDEXER=${IDX} -DSM_DENSE=${DENSE} -DSM_T1_B_HEADS=${B_HEADS} -DSM_U2_HOST_PTRS=${U2} -DSM_P0=${P0} -DSM_P1=${P1} -DSM_P2=${P2} -DSM_STAMPS=${STAMPS} -DSM_R1_RELAXED_SPIN=${R1} -DSM_R2_LIGHT_RELEASE=${R2} -DSM_R3_SRC_CREDIT=${R3} -DSM_R4_LAST_WG_FENCE=${R4} )
FLAGS=( "${VARDEFS[@]}" -I"${CAND}/device" -I"${CAND}/interface" -I"${PR695}/private_deps/aiter/csrc/include"
        -I"${MORI_ROOT}/include" -D__HIPCC_RTC__ -DBUILD_CCO_SDMA=1 -DOPUS_TILE_CONTAINER=0
        -std=c++20 -O3 -fno-fast-math --offload-arch=gfx950 )
{ echo "# SM-SK2-RAN-r2 device build variant P0=${P0} P1=${P1} P2=${P2} STAMPS=${STAMPS} R1=${R1} R2=${R2} R3=${R3} R4=${R4}"; "${HIPCC}" --version; echo "FLAGS: ${FLAGS[*]}"; } | tee "${BUILD_DIR}/build-command.txt"
build_one() {  # name src
  local n="$1" src="$2" so="${BUILD_DIR}/img/$1.so"
  "${HIPCC}" "${FLAGS[@]}" -fPIC -shared "${src}" -o "${so}"
  "${HIPCC}" "${FLAGS[@]}" --cuda-device-only -S "${src}" -o "${BUILD_DIR}/img/${n}.gfx950.s"
  "${OBJCOPY}" -O binary --only-section=.hip_fatbin "${so}" "${BUILD_DIR}/img/${n}.fatbin"
  local tgt; tgt="$("${BUNDLER}" --type=o --input="${BUILD_DIR}/img/${n}.fatbin" --list | grep gfx950 | head -n1)"
  [ -n "${tgt}" ] || { echo "NO gfx950 bundle entry in ${n}" >&2; exit 3; }
  "${BUNDLER}" --type=o --unbundle --targets="${tgt}" --input="${BUILD_DIR}/img/${n}.fatbin" --output="${BUILD_DIR}/img/${n}.hsaco"
  echo "${n}_BUILD_OK target=${tgt}"
}
build_one sm_gemm "${CAND}/device/sk_gemm_fp8.cu"
build_one sm_ran  "${CAND}/device/ran_kernel.cu"
GH="$(sha256sum "${BUILD_DIR}/img/sm_gemm.hsaco" | cut -d' ' -f1)"
RH="$(sha256sum "${BUILD_DIR}/img/sm_ran.hsaco" | cut -d' ' -f1)"
cat > "${BUILD_DIR}/gen/sm_expected_hashes.h" <<EOF
// GENERATED by SM-SK2-RAN-r2 build_device.sh (variant P0=${P0} P1=${P1} P2=${P2} STAMPS=${STAMPS} R1=${R1} R2=${R2} R3=${R3} R4=${R4}); actual code-object SHA256.
#pragma once
#define SM_EXPECTED_GEMM_SHA256 "${GH}"
#define SM_EXPECTED_RAN_SHA256 "${RH}"
EOF
cat "${BUILD_DIR}/gen/sm_expected_hashes.h"
