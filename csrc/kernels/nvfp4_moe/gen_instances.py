"""Kernel instance files of an NVFP4 MoE JIT module (moe_nvfp4_kernels.hip).

Without --names: every kernel of the shipped dispatch CSV and of the default
rule, split into --parts instance files. With --names: those kernels, in one
file. A registry file joins the parts' Instance arrays into the kernel table.
"""

import argparse
import importlib.util
import os
import sys

this_dir = os.path.dirname(os.path.abspath(__file__))
AITER_DIR = (
    os.path.abspath(f"{this_dir}/../../../../aiter")
    if os.path.exists(os.path.abspath(f"{this_dir}/../../../../aiter_meta"))
    else os.path.abspath(f"{this_dir}/../../../aiter")
)
DISPATCH_CSV = f"{AITER_DIR}/configs/moe_nvfp4_dispatch.csv"
sys.path.insert(0, f"{AITER_DIR}/jit/utils")
from moe_nvfp4_common import CFG_DEFAULTS, parse_kernel

# The dispatch policy (default rule, CSV) lives with the op; torch-free, by path
_spec = importlib.util.spec_from_file_location(
    "moe_nvfp4_dispatch", f"{AITER_DIR}/ops/moe_nvfp4_dispatch.py"
)
dispatch = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(dispatch)

X_ENUM = {"xreg": "X_REG", "xstream": "X_STREAM", "xres": "X_RESIDENT", "xdma": "X_DMA"}

PART = """// Generated by gen_instances.py.
#include "moe_nvfp4_kernels.hip"

// Not const: HIP would also emit a const array for the device (host launchers).
Instance moe_nvfp4_part{k}[] = {{
{kernels}
}};
"""

REGISTRY = """// Generated by gen_instances.py: the kernel table of this module.
#include "moe_nvfp4_kernels.hip"
#include "moe_nvfp4_entry.h"

{decls}
static const Instance* const g_instances[] = {{
{ptrs}
}};
constexpr int NUM_CFGS = {n};

extern "C" int moe_nvfp4_kernels_num_cfgs() {{ return NUM_CFGS; }}
extern "C" const char* moe_nvfp4_kernels_cfg_name(int i) {{ return g_instances[i]->name; }}
extern "C" void moe_nvfp4_kernels_cfg_info(int i, int* out)
{{
    const Cfg& c     = g_instances[i]->cfg;
    out[CFG_S1]      = c.s1;
    out[CFG_M_TILES] = c.m_tiles;
    out[CFG_N_TILES] = c.n_tiles;
    out[CFG_WAVES]   = c.waves;
    out[CFG_GS]      = c.gs;
    out[CFG_INBF16]  = c.inbf16;
    out[CFG_OUTBF16] = c.outbf16;
    out[CFG_REDUCE]  = c.reduce;
}}
extern "C" int moe_nvfp4_kernels_cfg_fits(int i, int K) {{ return g_instances[i]->fits(K); }}
extern "C" int
moe_nvfp4_kernels_launch(int kernel, const Params* hp, int grid_x, int grid_y, hipStream_t stream)
{{
    if(kernel < 0 || kernel >= NUM_CFGS)
        return -1;
    return g_instances[kernel]->launch(*hp, grid_x, grid_y, stream);
}}
"""


def write(path, text):
    with open(path, "w") as f:
        f.write(text)


def cfg_literal(name):
    """Cfg literal of a kernel name: its non-default fields, designated."""
    c = parse_kernel(name)
    v = {k: X_ENUM[x] if k == "x" else str(x).lower() for k, x in c.items()}
    fields = [f".{k} = {v[k]}" for k in c if c[k] != CFG_DEFAULTS[k]]
    return "Cfg{" + ", ".join(fields) + "}"


def generate(working_path, names, parts):
    names = sorted(set(names))
    cfgs = {n: cfg_literal(n) for n in names}
    os.makedirs(working_path, exist_ok=True)
    parts = max(1, min(parts, len(names)))
    decls, ptrs = [], []
    for k in range(parts):
        chunk = names[k::parts]
        kernels = "\n".join(f'    instance<{cfgs[n]}>("{n}"),' for n in chunk)
        write(f"{working_path}/moe_nvfp4_part{k}.cu", PART.format(k=k, kernels=kernels))
        decls.append(f"extern Instance moe_nvfp4_part{k}[];")
        ptrs += [f"    &moe_nvfp4_part{k}[{i}]," for i in range(len(chunk))]
    write(
        f"{working_path}/moe_nvfp4_registry.cu",
        REGISTRY.format(decls="\n".join(decls), ptrs="\n".join(ptrs), n=len(names)),
    )


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--working_path", required=True, help="output directory")
    ap.add_argument("--names", help="comma-separated kernel names (one part)")
    ap.add_argument("--parts", type=int, default=16, help="instance files")
    args = ap.parse_args()
    if args.names:
        generate(args.working_path, args.names.split(","), 1)
    else:
        names = dispatch.csv_names(DISPATCH_CSV) + dispatch.default_names()
        generate(args.working_path, names, args.parts)
