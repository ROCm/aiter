"""gfx950 bf16 grouped GEMM images: python3 build_co_a16w16_grouped.py --llvm-bin <AGPR-pinning LLVM>/bin.

One image per kid and layout, gen_co/gfx950/a16w16_grouped/<name>_<layout>.co (kid table
gen_co/co_kernels_gfx950_a16w16_grouped.json, opus_gemm_grouped_common.py). Each image's
extern "C" entry wraps gemm_a16w16_m_grouped_body (the 256 / 192 / 128-row tile bodies) or
gemm_a16w16_k_grouped_body<Traits> with the traits' launch bounds; the K-grouped images also
carry the plan kernel <symbol>_plan. Compiled, checked and recorded
(build_info.json) with build_co.py's helpers; the options are build_co.py's.
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile

import build_co  # also puts csrc/opus_gemm on sys.path
from opus_gemm_grouped_common import a16w16_grouped_kids_declared

# k_grouped: one tile size.
_K_STUB_TEMPLATE = """// SPDX-License-Identifier: MIT
// Copyright (C) 2025-2026, Advanced Micro Devices, Inc. All rights reserved.
//
// Auto-generated by csrc/opus_gemm/gen_co/build_co_a16w16_grouped.py. Do not edit or commit.
#include "gfx950/opus_gemm_pipeline_a16w16_grouped_gfx950.cuh"

using CoTraits = opus_gemm_a16w16_grouped_traits_gfx950<{bm}, {bn}, {b_t}, {k_grouped}, {c_f32}>;

extern "C" __global__ __launch_bounds__(CoTraits::BLOCK_SIZE, CoTraits::WG_PER_CU)
void {symbol}(opus_gemm_a16w16_grouped_kargs_t<CoTraits> kargs)
{{
#ifdef __HIP_DEVICE_COMPILE__
    gemm_a16w16_k_grouped_body<CoTraits>(kargs);
#else
    (void)kargs;
#endif
}}
{plan}"""

# m_grouped: the bodies of 256 / 192 / 128-row tiles in one kernel, picked per group.
_M_STUB_TEMPLATE = """// SPDX-License-Identifier: MIT
// Copyright (C) 2025-2026, Advanced Micro Devices, Inc. All rights reserved.
//
// Auto-generated by csrc/opus_gemm/gen_co/build_co_a16w16_grouped.py. Do not edit or commit.
#include "gfx950/opus_gemm_pipeline_a16w16_grouped_gfx950.cuh"

using CoTraits0 = opus_gemm_a16w16_grouped_traits_gfx950<256, {bn}, {b_t}>;
using CoTraits1 = opus_gemm_a16w16_grouped_traits_gfx950<192, {bn}, {b_t}>;
using CoTraits2 = opus_gemm_a16w16_grouped_traits_gfx950<128, {bn}, {b_t}>;

extern "C" __global__ __launch_bounds__(CoTraits0::BLOCK_SIZE, CoTraits0::WG_PER_CU)
void {symbol}(opus_gemm_a16w16_grouped_kargs_gfx950 kargs)
{{
#ifdef __HIP_DEVICE_COMPILE__
    gemm_a16w16_m_grouped_body<CoTraits0, CoTraits1, CoTraits2>(kargs);
#else
    (void)kargs;
#endif
}}
"""

_PLAN_TEMPLATE = """
extern "C" __global__ __launch_bounds__(OPUS_K_GROUPED_PLAN_THREADS)
void {symbol}_plan(opus_gemm_a16w16_k_grouped_plan_kargs_gfx950 kargs)
{{
#if defined(__HIP_DEVICE_COMPILE__) && defined(__gfx950__)
    opus_a16w16_grouped::k_grouped_plan_body(kargs);
#else
    (void)kargs;
#endif
}}
"""

# sizeof the kargs structs of include/gfx950/opus_gemm_traits_a16w16_grouped_gfx950.cuh
_KARGS_BYTES = {"m_grouped": 88, "k_grouped": 80}
_PLAN_KARGS_BYTES = 3 * 8 + 6 * 4


def _cpp_bool(value):
    return "true" if value else "false"


def _jobs(kids):
    return [
        {"k": k, "layout": layout, "symbol": symbol}
        for k in kids
        for layout, symbol in k.images()
    ]


def _build_one(job, co, args, llvm_bin, workdir):
    k, layout, symbol = job["k"], job["layout"], job["symbol"]
    k_grouped = k.kind == "k_grouped"
    stub_path = os.path.join(workdir, f"{symbol}.cc")
    template = _K_STUB_TEMPLATE if k_grouped else _M_STUB_TEMPLATE
    with open(stub_path, "w") as f:
        f.write(
            template.format(
                bm=k.B_M,
                bn=k.B_N,
                b_t=_cpp_bool(layout != "nt"),
                k_grouped=_cpp_bool(k_grouped),
                c_f32=_cpp_bool(layout.endswith("_f32")),
                symbol=symbol,
                plan=_PLAN_TEMPLATE.format(symbol=symbol) if k_grouped else "",
            )
        )
    out_path = os.path.join(args.out_dir, f"{symbol}.co")
    device_flags = list(args.device_flag)
    common = [
        *args.hipcc.split(),
        "-x",
        "hip",
        f"--offload-arch={args.offload_arch}",
        "-std=c++20",
        "-O3",
        # No host runtime wrapper / hidden kernargs: launched through
        # HIP_LAUNCH_PARAM_BUFFER_POINTER with exactly the kargs bytes.
        "-D__HIPCC_RTC__",
        "-Werror=ignored-attributes",
        # opus.hpp deduction guides carry __host__ __device__ (newer clang warns).
        "-Wno-deprecated-attributes",
        f"-I{co._CSRC_DIR}/include",
        f"-I{co._OPUS_GEMM_DIR}/include",
        *device_flags,
    ]
    env = dict(os.environ)
    if llvm_bin:
        env["HIP_CLANG_PATH"] = llvm_bin

    def run_compile(extra, out, what):
        proc = subprocess.run(
            [*common, *extra, "-o", out, stub_path],
            capture_output=True,
            text=True,
            env=env,
            check=False,
        )
        if proc.returncode != 0:
            sys.stderr.write(proc.stdout)
            sys.stderr.write(proc.stderr)
            raise SystemExit(f"build_co: hipcc failed for {symbol} ({what})")
        if proc.stderr.strip():
            sys.stderr.write(proc.stderr)

    print(f"[build_co] compiling {symbol}")
    run_compile(["--genco"], out_path, "genco")
    unbundled = co._unbundle_if_needed(out_path, llvm_bin, args.offload_arch)

    readelf = co._tool(llvm_bin, "llvm-readelf")
    symbols = (symbol, f"{symbol}_plan") if k_grouped else (symbol,)
    md = co._kernel_metadata(readelf, out_path, symbol, expected_symbols=symbols)
    target_md = co._elf_target_metadata(out_path, args.offload_arch)
    target_md.update(co._device_link_metadata(readelf, out_path))
    expected = {symbol: _KARGS_BYTES[k.kind]}
    if k_grouped:
        expected[f"{symbol}_plan"] = _PLAN_KARGS_BYTES
    for sym, kargs_bytes in expected.items():
        got = co._kernel_metadata(readelf, out_path, sym, expected_symbols=symbols)
        if got["kernarg_segment_size"] != kargs_bytes:
            raise SystemExit(
                f"build_co: {sym} kernarg mismatch: .co says "
                f"{got['kernarg_segment_size']}, host ABI requires {kargs_bytes}"
            )
    if md["vgpr_spill_count"] or md["sgpr_spill_count"]:
        msg = (
            f"{symbol} spills (vgpr={md['vgpr_spill_count']}, "
            f"sgpr={md['sgpr_spill_count']})"
        )
        if args.fail_on_spill:
            raise SystemExit(f"build_co: {msg} and --fail-on-spill is set")
        print(f"[build_co]   WARNING: {msg}", file=sys.stderr)

    with open(out_path, "rb") as f:
        co_sha256 = hashlib.sha256(f.read()).hexdigest()
    info = {
        "symbol": symbol,
        "co_sha256": co_sha256,
        "kid": k.kid,
        "kind": k.kind,
        "tile": [k.B_M, k.B_N, 64],
        "layout": layout,
        "device_flags": device_flags,
        **target_md,
        **md,
    }
    if not args.no_asm:
        asm_dir = os.path.join(args.out_dir, "asm")
        os.makedirs(asm_dir, exist_ok=True)
        run_compile(
            ["-S", "--cuda-device-only"], os.path.join(asm_dir, f"{symbol}.s"), "-S"
        )
    print(
        f"[build_co]   {symbol}: VGPR={md['vgpr_count']} "
        f"SGPR={md['sgpr_count']} LDS={md['group_segment_fixed_size']} "
        f"kernarg={md['kernarg_segment_size']} spill={md['vgpr_spill_count']}/"
        f"{md['sgpr_spill_count']} {'(unbundled)' if unbundled else '(bare ELF)'}"
    )
    return info


def build(p, args, llvm_bin, co):
    """Build the selected kids (--kids, default all) into args.out_dir + build_info.json."""
    declared = a16w16_grouped_kids_declared
    kids = [declared[kid] for kid in sorted(declared)]
    if args.kids:
        try:
            selected = {
                int(kid.strip()) for token in args.kids for kid in token.split(",")
            }
        except ValueError:
            p.error("--kids must contain integer kids separated by spaces or commas")
        unknown = selected - set(declared)
        if unknown:
            p.error(f"unknown gfx950 grouped kids: {sorted(unknown)}")
        kids = [k for k in kids if k.kid in selected]
    jobs = _jobs(kids)
    if not jobs:
        raise SystemExit(
            "build_co: no entries -- check gen_co/co_kernels_gfx950_a16w16_grouped.json"
        )
    n_jobs = co.get_worker_count_for(len(jobs), args.jobs)
    workdir = tempfile.mkdtemp(prefix="opus_build_co_gfx950_grouped_")
    try:
        if n_jobs == 1:
            built = [_build_one(j, co, args, llvm_bin, workdir) for j in jobs]
        else:
            from concurrent.futures import ThreadPoolExecutor

            print(f"[build_co] {len(jobs)} images on {n_jobs} jobs")
            with ThreadPoolExecutor(max_workers=n_jobs) as pool:
                built = list(
                    pool.map(lambda j: _build_one(j, co, args, llvm_bin, workdir), jobs)
                )
    finally:
        if args.keep_temps:
            print(f"[build_co] stub TUs kept in {workdir}")
        else:
            shutil.rmtree(workdir, ignore_errors=True)
    built.sort(key=lambda b: (b["kid"], b["symbol"]))

    try:
        clang = os.path.join(llvm_bin, "clang") if llvm_bin else "clang"
        ver = co._run([clang, "--version"]).stdout.strip().splitlines()[0]
    except Exception:  # noqa: BLE001
        ver = "unknown"
    info = {
        "arch": args.arch,
        "offload_arch": args.offload_arch,
        "hipcc": args.hipcc,
        "device_clang": ver,
        "hip_clang_path": llvm_bin,
        "common_flags": [
            "-D__HIPCC_RTC__",
            "-O3",
            "-std=c++20",
            "-Werror=ignored-attributes",
            "-Wno-deprecated-attributes",
        ],
        "kernels": built,
    }
    info_path = os.path.join(args.out_dir, "build_info.json")
    with open(info_path, "w") as f:
        json.dump(info, f, indent=2, sort_keys=True)
        f.write("\n")
    spills = sum(1 for b in built if b["vgpr_spill_count"] or b["sgpr_spill_count"])
    print(
        f"[build_co] wrote {len(built)} gfx950 .co ({spills} with spills) + {info_path}"
    )


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument(
        "--hipcc",
        default=os.environ.get("HIPCC", "/opt/rocm/bin/hipcc"),
        help="hipcc driver; default /opt/rocm/bin/hipcc",
    )
    p.add_argument(
        "--llvm-bin",
        dest="llvm_bin",
        default=os.environ.get("OPUS_CO_LLVM_BIN", ""),
        help="bin/ of the AGPR-pinning LLVM build (HIP_CLANG_PATH); default $OPUS_CO_LLVM_BIN",
    )
    p.add_argument("--device-flag", action="append", default=[], metavar="FLAG")
    p.add_argument(
        "--out-dir",
        default=os.path.join(build_co._HERE, "gfx950", "a16w16_grouped"),
        help="default: gen_co/gfx950/a16w16_grouped",
    )
    p.add_argument("--no-asm", action="store_true")
    p.add_argument("--fail-on-spill", action="store_true")
    p.add_argument("--jobs", "-j", type=int, default=None, help=build_co.JOBS_CLI_HELP)
    p.add_argument(
        "--kids", nargs="+", default=None, help="kids to rebuild (default: all)"
    )
    p.add_argument("--keep-temps", action="store_true")
    args = p.parse_args()
    args.arch = args.offload_arch = "gfx950"
    os.makedirs(args.out_dir, exist_ok=True)
    llvm_bin = os.path.abspath(args.llvm_bin) if args.llvm_bin else ""
    print(f"[build_co] clang from: {llvm_bin or '(PATH / hipcc default)'}")
    build(p, args, llvm_bin, build_co)


if __name__ == "__main__":
    main()
