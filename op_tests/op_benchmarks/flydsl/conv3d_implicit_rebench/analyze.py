"""Turn bench_all.py's results.jsonl into the markdown tables of the report.

python3 analyze.py [data_dir]       # prints markdown to stdout; default ./data
"""

import itertools
import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

PEAK_TF = 2500.0  # gfx950 / MI355X dense BF16 MFMA, theoretical
PEAK_BW = 8000.0  # HBM3E, GB/s, theoretical
RIDGE = PEAK_TF * 1e12 / (PEAK_BW * 1e9)

GROUPS = [
    ("wan21", "480x832", "Wan2.1 VAE 480×832 @81f"),
    ("wan21", "368x544", "Wan2.1 VAE 368×544 @81f"),
    ("qwenimage", "1328x1328", "Qwen-Image VAE 1328²"),
    ("qwenimage", "1024x1024", "Qwen-Image VAE 1024²"),
]


def load(d):
    with open(os.path.join(d, "meta.json")) as f:
        meta = json.load(f)
    with open(os.path.join(d, "results.jsonl")) as f:
        recs = [json.loads(line) for line in f]
    rows = []
    for r in recs:
        for model, res, case, calls in r["cases"] or [[r["model"], "?", "?", 0]]:
            rows.append({**r, "res": res, "case": case, "calls": calls})
    df = pd.DataFrame(rows)
    flops = 2.0 * df.M * df.N * df.K
    df["AI"] = flops / df.bytes
    for tag, col in (
        ("k", "kernel_us"),
        ("s", "kernel_us_sus"),
        ("e", "e2e_us"),
        ("c", "csv_us"),
    ):
        df[f"tf_{tag}"] = flops / (df[col] * 1e-6) / 1e12
        df[f"bw_{tag}"] = df.bytes / (df[col] * 1e-6) / 1e9
        df[f"mfma_{tag}"] = df[f"tf_{tag}"] / PEAK_TF * 100
        df[f"hbm_{tag}"] = df[f"bw_{tag}"] / PEAK_BW * 100
    df["bound"] = np.where(df.AI >= RIDGE, "compute", "memory")
    roof = np.minimum(meta["mm_tflops"], df.AI * meta["copy_gbs"] / 1e3)
    df["ach_k"] = df.tf_k / roof * 100
    df["d_e2e"] = (df.e2e_us / df.csv_us - 1) * 100
    df["d_sus"] = (df.kernel_us_sus / df.kernel_us - 1) * 100
    df["d_hotw"] = (df.kernel_us / df.kernel_us_csvproto - 1) * 100
    df["ms_pass_e"] = df.e2e_us * df.calls / 1e3
    df["ms_pass_k"] = df.kernel_us * df.calls / 1e3
    df["ms_pass_s"] = df.kernel_us_sus * df.calls / 1e3
    df["ms_pass_c"] = df.csv_us * df.calls / 1e3
    df["spread"] = df.rep_kernel_us.apply(lambda v: (max(v) / min(v) - 1) * 100)
    return meta, df


def q(s, w=None):
    out = [s.min(), s.median(), s.max()]
    if w is not None:
        out.append(float((s * w).sum() / w.sum()))
    return out


def main():
    d = (
        sys.argv[1]
        if len(sys.argv) > 1
        else str(Path(__file__).resolve().parent / "data")
    )
    meta, df = load(d)
    p = print
    p(f"<!-- generated by analyze.py from {os.path.abspath(d)} -->")
    p()
    p(
        f"- device: {meta['gfx']} / {meta['cu_num']} CU, HIP_VISIBLE_DEVICES={meta['hip_visible_devices']}, torch {meta['torch']}"
    )
    p(
        f"- torch.mm 8192³ bf16: burst **{meta['mm_tflops']:.0f}** / sustained **{meta['mm_tflops_sus']:.0f}** TFLOPS；"
        f"D2D copy（读+写）: burst **{meta['copy_gbs']:.0f}** / sustained **{meta['copy_gbs_sus']:.0f}** GB/s"
    )
    p(
        f"- rows={len(df)}, status ok={int((df.status == 'ok').sum())}, lookup ok={int(df.lookup_ok.sum())}, "
        f"mismatch>0 rows={int((df.mismatch > 0).sum())}, 3 次 kernel 时间极差中位 {df.spread.median():.1f}%、最大 {df.spread.max():.1f}%"
    )
    p()

    w = df.ms_pass_k
    p("### 汇总统计")
    p()
    p("| 指标 | 最小 | 中位 | 最大 | 按 calls×时间加权 |")
    p("|---|---:|---:|---:|---:|")
    for name, col in (
        ("MFMA 利用率 %（kernel-only, burst）", "mfma_k"),
        ("HBM 带宽利用率 %（kernel-only, burst）", "hbm_k"),
        ("MFMA 利用率 %（kernel-only, sustained）", "mfma_s"),
        ("MFMA 利用率 %（e2e, CSV 协议）", "mfma_e"),
        ("达成率 %（相对同卡实测 roofline）", "ach_k"),
        ("sustained 相对 burst 变慢 %", "d_sus"),
    ):
        v = q(df[col], w)
        p(f"| {name} | {v[0]:.1f} | {v[1]:.1f} | {v[2]:.1f} | {v[3]:.1f} |")
    v = q(df.d_e2e)
    p(f"| e2e 相对 CSV `us` 偏差 % | {v[0]:+.1f} | {v[1]:+.1f} | {v[2]:+.1f} | — |")
    p()
    for b in ("compute", "memory"):
        s = df[df.bound == b]
        p(
            f"- {b}-bound {len(s)} 行：MFMA% 中位 {s.mfma_k.median():.1f}（最高 {s.mfma_k.max():.1f}），"
            f"HBM% 中位 {s.hbm_k.median():.1f}（最高 {s.hbm_k.max():.1f}），达成率中位 {s.ach_k.median():.1f}"
        )
    p()

    p("### 按达成率分档")
    p()
    p("| 达成率区间 | 行数 | kernel-only ms/pass | 占比 |")
    p("|---|---:|---:|---:|")
    edges = [0, 20, 35, 50, 65, 100]
    for lo, hi in itertools.pairwise(edges):
        s = df[(df.ach_k > lo) & (df.ach_k <= hi)]
        p(
            f"| ({lo}, {hi}] | {len(s)} | {s.ms_pass_k.sum():.1f} | {s.ms_pass_k.sum() / w.sum() * 100:.1f}% |"
        )
    p()

    p("### MFMA 利用率最高的 5 行")
    p()
    p("| case | res | kernel us | TFLOPS | MFMA% | 达成率% |")
    p("|---|---|---:|---:|---:|---:|")
    for _, r in df.sort_values("mfma_k", ascending=False).head(5).iterrows():
        p(
            f"| `{r.case}` | {r.res} | {r.kernel_us:.1f} | {r.tf_k:.0f} | {r.mfma_k:.1f} | {r.ach_k:.1f} |"
        )
    p()

    p("### HBM 带宽利用率最高的 5 行")
    p()
    p("| case | res | kernel us | GB/s | HBM% | AI | bound | 达成率% |")
    p("|---|---|---:|---:|---:|---:|---|---:|")
    for _, r in df.sort_values("hbm_k", ascending=False).head(5).iterrows():
        p(
            f"| `{r.case}` | {r.res} | {r.kernel_us:.1f} | {r.bw_k:.0f} | {r.hbm_k:.1f} | {r.AI:.0f} | {r.bound[:3]} | {r.ach_k:.1f} |"
        )
    p()

    p("### 每 pass 合计")
    p()
    p(
        "| 模型 / 分辨率 | 行数 | CSV ms | e2e ms（CSV 协议） | kernel-only ms（burst） | kernel-only ms（sustained） | 耗时加权 MFMA% |"
    )
    p("|---|---:|---:|---:|---:|---:|---:|")
    for model, res, title in GROUPS:
        s = df[(df.model == model) & (df.res == res)]
        wm = (s.mfma_k * s.ms_pass_k).sum() / s.ms_pass_k.sum()
        p(
            f"| {title} | {len(s)} | {s.ms_pass_c.sum():.1f} | {s.ms_pass_e.sum():.1f} | "
            f"{s.ms_pass_k.sum():.1f} | {s.ms_pass_s.sum():.1f} | {wm:.1f} |"
        )
    p()

    for model, res, title in GROUPS:
        s = df[(df.model == model) & (df.res == res)].sort_values(
            "ms_pass_k", ascending=False
        )
        p(f"### {title}")
        p()
        p(
            "| case | calls | M | N | K | tile/wave | CSV us | e2e us | Δ | kernel us | sustained us | TFLOPS | MFMA% | GB/s | HBM% | AI | bound | 达成率% | ms/pass |"
        )
        p(
            "|---|---:|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|---:|"
        )
        for _, r in s.iterrows():
            p(
                f"| `{r.case}` | {r.calls} | {r.M:,} | {r.N} | {r.K} | {r.tile} | {r.csv_us:.1f} | "
                f"{r.e2e_us:.1f} | {r.d_e2e:+.1f}% | {r.kernel_us:.1f} | {r.kernel_us_sus:.1f} | "
                f"{r.tf_k:.0f} | {r.mfma_k:.1f} | {r.bw_k:.0f} | {r.hbm_k:.1f} | {r.AI:.0f} | "
                f"{r.bound[:3]} | {r.ach_k:.1f} | {r.ms_pass_k:.2f} |"
            )
        p()

    p("### e2e 与 CSV 偏差超过 ±5% 的行")
    p()
    big = df[df.d_e2e.abs() > 5].sort_values("d_e2e")
    p("| case | res | CSV us | e2e us | Δ | 3 次 e2e |")
    p("|---|---|---:|---:|---:|---|")
    for _, r in big.iterrows():
        p(
            f"| `{r.case}` | {r.res} | {r.csv_us:.1f} | {r.e2e_us:.1f} | {r.d_e2e:+.1f}% | "
            f"{' / '.join(f'{v:.1f}' for v in r.rep_e2e_us)} |"
        )
    p()

    p("### 热权重效应：CSV 协议下 conv kernel 比权重缓存命中时快的行（>5%）")
    p()
    hw = df[df.d_hotw > 5].sort_values("d_hotw", ascending=False)
    p(
        "| case | res | M | N | K | 权重 MB | x MB | kernel us（CSV 协议） | kernel us（缓存命中） | 差 |"
    )
    p("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for _, r in hw.iterrows():
        k = r.key
        wmb = k[5] * k[1] * k[6] * k[7] * k[8] * 2 / 2**20
        xmb = k[0] * k[1] * k[2] * k[3] * k[4] * 2 / 2**20
        p(
            f"| `{r.case}` | {r.res} | {r.M:,} | {r.N} | {r.K} | {wmb:.1f} | {xmb:.1f} | "
            f"{r.kernel_us_csvproto:.1f} | {r.kernel_us:.1f} | {r.d_hotw:+.1f}% |"
        )
    p()

    p("### sustained 相对 burst 变慢最多的 10 行")
    p()
    p(
        "| case | res | kernel us（burst） | sustained us | 变慢 | MFMA%（burst） | HBM%（burst） |"
    )
    p("|---|---|---:|---:|---:|---:|---:|")
    for _, r in df.sort_values("d_sus", ascending=False).head(10).iterrows():
        p(
            f"| `{r.case}` | {r.res} | {r.kernel_us:.1f} | {r.kernel_us_sus:.1f} | {r.d_sus:+.1f}% | {r.mfma_k:.1f} | {r.hbm_k:.1f} |"
        )
    p()

    aux = df[df.aux_us > 0.5]
    if len(aux):
        p("### 缓存命中后每次调用仍有的额外 kernel")
        p()
        for _, r in aux.iterrows():
            p(f"- `{r.case}` @{r.res}: {r.aux_us:.1f} us/call, {r.aux_kernels}")
        p()


if __name__ == "__main__":
    main()
