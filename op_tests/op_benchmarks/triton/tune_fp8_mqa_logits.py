"""
Offline tuner for the non-gluon Triton fp8_mqa_logits (DSA/NSA indexer) kernel.

Sweeps the (BLOCK_KV, num_stages) tile candidates over the head sizes and
sequence-length buckets the kernel dispatches on, and writes the result to
    aiter/ops/triton/configs/{arch}-FP8_MQA_LOGITS.json
so that nothing has to be tuned at runtime.

Usage (on the target GPU):
    python op_tests/op_benchmarks/triton/tune_fp8_mqa_logits.py
    python op_tests/op_benchmarks/triton/tune_fp8_mqa_logits.py \
        --head_dims 128 --num_heads_q 64 --o my-config.json --dry_run
"""

import argparse
import json
import os

import torch
import triton

from aiter.ops.triton.attention.fp8_mqa_logits import (
    _MQA_SEQ_BUCKETS,
    fp8_mqa_logits,
)
from aiter.ops.triton.utils._triton import arch_info
from aiter.ops.triton.utils.core import AITER_TRITON_CONFIGS_PATH
from aiter.ops.triton.utils.types import e4m3_dtype
from op_tests.triton_tests.attention.test_fp8_mqa_logits import (
    per_custom_dims_cast_to_fp8,
)

# Candidate tiles, largest first. Anything that does not compile on this
# Triton/arch (e.g. an LDS overflow) is skipped.
TILE_CANDIDATES = [(128, 2), (128, 1), (64, 2), (64, 1)]


def make_inputs(seq_len, num_heads_q, head_dim):
    q = torch.randn(seq_len, num_heads_q, head_dim, device="cuda", dtype=torch.bfloat16)
    kv = torch.randn(seq_len, head_dim, device="cuda", dtype=torch.bfloat16)
    kv_fp8, scales = per_custom_dims_cast_to_fp8(kv, (0,), False)
    weights = torch.randn(seq_len, num_heads_q, device="cuda", dtype=torch.float32)
    ks = torch.zeros(seq_len, dtype=torch.int, device="cuda")
    ke = torch.arange(seq_len, dtype=torch.int, device="cuda") + 1
    q_fp8 = q.to(e4m3_dtype)
    return q_fp8, kv_fp8, scales, weights, ks, ke


def bench_tile(inputs, block_kv, num_stages, warmup, rep):
    q_fp8, kv_fp8, scales, weights, ks, ke = inputs
    config = {"BLOCK_KV": block_kv, "num_stages": num_stages}

    def func():
        return fp8_mqa_logits(
            q_fp8, kv_fp8, scales, weights, ks, ke, True, config=config
        )

    try:
        func()  # compile probe: a tile that does not fit is skipped, not fatal
    except Exception as e:  # noqa: BLE001
        return None, f"skip ({type(e).__name__})"
    return triton.testing.do_bench(func, warmup=warmup, rep=rep), None


def tune(args):
    out = {
        "_comment": (
            "Tile configs for the non-gluon Triton fp8_mqa_logits (DSA/NSA "
            "indexer) kernel. Generated by "
            "op_tests/op_benchmarks/triton/tune_fp8_mqa_logits.py."
        ),
        "default": {"BLOCK_KV": 128, "num_stages": 2},
    }
    buckets = list(_MQA_SEQ_BUCKETS) if args.seq_lens is None else args.seq_lens
    for head_dim in args.head_dims:
        head_entry = {}
        for seq_len in buckets:
            inputs = make_inputs(seq_len, args.num_heads_q, head_dim)
            best, best_t = None, float("inf")
            for block_kv, num_stages in TILE_CANDIDATES:
                t, err = bench_tile(inputs, block_kv, num_stages, args.warmup, args.rep)
                print(
                    f"head_dim={head_dim} seq_len={seq_len} "
                    f"tile=({block_kv},{num_stages}): "
                    + (err if err else f"{t:.4f} ms")
                )
                if t is not None and t < best_t:
                    best, best_t = (block_kv, num_stages), t
            if best is None:
                # Nothing compiled; the runtime LDS guard would land here too.
                best = (64, 1)
            key = (
                f"SEQ_LEN_LEQ_{seq_len}"
                if seq_len <= _MQA_SEQ_BUCKETS[-1]
                else f"SEQ_LEN_GT_{_MQA_SEQ_BUCKETS[-1]}"
            )
            head_entry[key] = {"BLOCK_KV": best[0], "num_stages": best[1]}
            del inputs
            torch.cuda.empty_cache()
        out[f"HEAD_SIZE={head_dim}"] = head_entry
    return out


def main():
    parser = argparse.ArgumentParser(
        description="Offline tuner for Triton fp8_mqa_logits tiles",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--num_heads_q", type=int, default=64, help="num. q heads")
    parser.add_argument(
        "--head_dims", type=int, nargs="+", default=[128], help="head dims to tune"
    )
    parser.add_argument(
        "--seq_lens",
        type=int,
        nargs="+",
        default=None,
        help="seq lens to tune (default: the kernel's bucket boundaries)",
    )
    parser.add_argument("--warmup", type=int, default=25)
    parser.add_argument("--rep", type=int, default=100)
    parser.add_argument("--o", type=str, default=None, help="output json path")
    parser.add_argument(
        "--dry_run", action="store_true", help="print the config instead of writing it"
    )
    args = parser.parse_args()

    arch = arch_info.get_arch()
    config = tune(args)
    text = json.dumps(config, indent=2) + "\n"
    if args.dry_run:
        print(text)
        return
    fpath = args.o or os.path.join(
        AITER_TRITON_CONFIGS_PATH, f"{arch}-FP8_MQA_LOGITS.json"
    )
    with open(fpath, "w") as f:
        f.write(text)
    print(f"wrote {fpath}")


if __name__ == "__main__":
    main()
