#!/bin/bash
# Sweep HIP runtime knobs on the per-kernel cost of a graph of tiny kernels (GPU 0).
cd /w
export HSA_OVERRIDE_GFX_VERSION=12.5.0 HIP_VISIBLE_DEVICES=0
run() {
    local label="$1"; shift
    local r
    r=$(for i in 1 2 3; do env "$@" python3 graph_gap.py 1000 2>/dev/null | tail -1 | sed 's/.*: \([0-9.]*\) us\/kernel.*/\1/'; done | tr '\n' ' ')
    printf "%-45s %s\n" "$label" "$r"
}
run "baseline" A=1
run "DEBUG_HIP_GRAPH_CLASSIC_PATH=1" DEBUG_HIP_GRAPH_CLASSIC_PATH=1
run "DEBUG_HIP_GRAPH_SEGMENT_SCHEDULING=1" DEBUG_HIP_GRAPH_SEGMENT_SCHEDULING=1
run "DEBUG_HIP_GRAPH_SEGMENT_SCHEDULING=0" DEBUG_HIP_GRAPH_SEGMENT_SCHEDULING=0
run "DEBUG_HIP_GRAPH_BATCH_SIZE=1024" DEBUG_HIP_GRAPH_BATCH_SIZE=1024
run "DEBUG_CLR_MAX_BATCH_SIZE=1024" DEBUG_CLR_MAX_BATCH_SIZE=1024
run "HIP_FORCE_DEV_KERNARG=1" HIP_FORCE_DEV_KERNARG=1
run "HIP_FORCE_DEV_KERNARG=0" HIP_FORCE_DEV_KERNARG=0
run "ROC_USE_FGS_KERNARG=0" ROC_USE_FGS_KERNARG=0
run "ROC_SKIP_KERNEL_ARG_COPY=1" ROC_SKIP_KERNEL_ARG_COPY=1
run "ROC_SYSTEM_SCOPE_SIGNAL=0" ROC_SYSTEM_SCOPE_SIGNAL=0
run "DEBUG_CLR_DIRECT_DOORBELL=1" DEBUG_CLR_DIRECT_DOORBELL=1
run "DEBUG_CLR_DOORBELL_SKIP=1" DEBUG_CLR_DOORBELL_SKIP=1
run "AMD_DIRECT_DISPATCH=0" AMD_DIRECT_DISPATCH=0
run "GPU_FLUSH_ON_EXECUTION=0" GPU_FLUSH_ON_EXECUTION=0
run "GPU_ENABLE_WGP_MODE=0" GPU_ENABLE_WGP_MODE=0
run "GPU_ENABLE_WGP_MODE=1" GPU_ENABLE_WGP_MODE=1
